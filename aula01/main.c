// está incluindo uma biblioteca padrão de entrada e saída, que permite utilizar funções como printf para exibir mensagens no console.
// sem essa biblioteca, não seria possível utilizar a função printf para imprimir "Hello, World" na tela, pois ela fornece as definições necessárias para a função funcionar corretamente.
#include <stdio.h>

// função main é o ponto de entrada do programa, onde a execução começa. Quando o compilador vai tentar compilar o programa, ele procura pela função main para iniciar a execução do código.
void main() {
    printf("Hello, World");
}